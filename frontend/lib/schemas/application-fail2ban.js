import { z } from "zod";

/**
 * One site's fail2ban — the raw-INI form.
 *
 * A different feature from the server-level one: this jail watches this site's
 * own access log, not the system's auth logs. It used to be a structured
 * payload (an enable flag, a jail list, banned addresses, counters); the
 * backend replaced all of that with two INI blobs written verbatim to
 * `/etc/fail2ban/{jail,filter}.d/`, so the screen is now an editor rather than
 * a dashboard.
 *
 * `fail2ban` is null until the site has been set up — which is not the same as
 * "off with empty settings", and the screen says so differently.
 */
const savedFail2banSchema = z.object({
  // `sVoss-<slug>`. Generated by the backend; shown, never typed.
  jail_name: z.string().nullish(),
  jail_content: z.string(),
  filter_content: z.string(),
});

export const applicationFail2banResponseSchema = z.object({
  fail2ban: savedFail2banSchema.nullable().default(null),
  // Once a site IS configured these echo the saved content rather than the
  // shipped defaults, so they are only a starting point for a site that has
  // none — never a way back to default. See `memory/backend-asks.md`.
  jail_template: z.string().default(""),
  filter_template: z.string().default(""),
});

/**
 * The placeholders the backend substitutes when it writes the files.
 *
 * They must survive editing: a user who "fills them in" with a real path gets
 * a jail that works until the site moves. The editor warns rather than
 * blocking, because a legitimate config can name an extra logpath directly.
 */
export const FAIL2BAN_PLACEHOLDERS = ["{name}", "{filter}", "{logpath}", "{slug}"];

/** Which of the placeholders a draft has lost, so the warning can name them. */
export function missingPlaceholders(original = "", draft = "") {
  return FAIL2BAN_PLACEHOLDERS.filter(
    (token) => original.includes(token) && !draft.includes(token),
  );
}

/**
 * `CustomFail2banRequest`: both halves required, 65535 bytes each.
 *
 * Checked here so an empty editor is refused in the field rather than after a
 * round trip — the backend rejects a half-empty submission because fail2ban
 * would load a jail whose filter does not exist.
 */
const iniContent = z.string().trim().min(1, "required").max(65535, "max65535");

export const fail2banConfigFormSchema = z.object({
  jail_config_content: iniContent,
  filter_config_content: iniContent,
});
